package dev.symbiosis.runtime.telephony

import kotlin.math.PI
import kotlin.math.cos
import kotlin.math.ln
import kotlin.math.log10
import kotlin.math.max
import kotlin.math.min
import kotlin.math.sin
import kotlin.math.sqrt

/**
 * Whisper's log-mel front end, as `transformers.WhisperFeatureExtractor` computes it, for 16 kHz mono audio.
 *
 * This exists because smart-turn v3 ([TurnDetector]) is a Whisper-Tiny encoder and expects exactly these
 * features: 80 slaney-normalised mel bands over a 400-point periodic Hann STFT with hop 160, reflect-padded,
 * `log10` with a 1e-10 floor, clamped to (max - 8), then `(x + 4) / 4`. The extractor drops the last STFT
 * frame, so 8 s of audio gives 800 frames. With `do_normalize=True` the *waveform* is first scaled to zero
 * mean / unit variance over the whole window (including any leading zero padding).
 *
 * Verified against the reference implementation in `TurnDetectorTest` (golden vectors generated by Python).
 *
 * Cost matters: this runs on the capture thread at every pause. Two things keep it in the ~10 ms range on the
 * phone: a mixed-radix FFT for the 400-point transform (400 = 2^4·5^2, so a power-of-two FFT would not be
 * exact), and skipping the frames that lie entirely inside the constant left padding — for a 2 s turn that
 * is three quarters of the window, and every one of those frames has the same spectrum.
 */
object WhisperMel {
  const val SAMPLE_RATE = 16_000
  const val N_FFT = 400
  const val HOP = 160
  const val N_MELS = 80
  private const val N_BINS = N_FFT / 2 + 1 // 201

  private val window = DoubleArray(N_FFT) { 0.5 - 0.5 * cos(2.0 * PI * it / N_FFT) } // periodic Hann
  /** (N_BINS x N_MELS) triangular filters, slaney scale and slaney norm, 0..8000 Hz. */
  private val mel = DoubleArray(N_BINS * N_MELS)

  init {
    // transformers.audio_utils.mel_filter_bank(norm="slaney", mel_scale="slaney")
    fun hzToMel(f: Double): Double =
      if (f >= 1000.0) 15.0 + ln(f / 1000.0) * (27.0 / ln(6.4)) else 3.0 * f / 200.0
    fun melToHz(m: Double): Double =
      if (m >= 15.0) 1000.0 * Math.exp((m - 15.0) * ln(6.4) / 27.0) else 200.0 * m / 3.0
    val melMin = hzToMel(0.0); val melMax = hzToMel(8000.0)
    val filterHz = DoubleArray(N_MELS + 2) { melToHz(melMin + (melMax - melMin) * it / (N_MELS + 1)) }
    val fftHz = DoubleArray(N_BINS) { it * SAMPLE_RATE / 2.0 / (N_BINS - 1) }
    for (m in 0 until N_MELS) {
      val lo = filterHz[m]; val mid = filterHz[m + 1]; val hi = filterHz[m + 2]
      val enorm = 2.0 / (hi - lo)
      for (k in 0 until N_BINS) {
        val f = fftHz[k]
        val down = (f - lo) / (mid - lo)
        val up = (hi - f) / (hi - mid)
        mel[k * N_MELS + m] = max(0.0, min(down, up)) * enorm
      }
    }
  }

  /** Number of feature frames for [samples] samples of audio (8 s -> 800). */
  fun frames(samples: Int): Int = samples / HOP

  /**
   * Compute features for exactly [pcm] (16 kHz, 16-bit). Returns a row-major (N_MELS x frames) float array,
   * i.e. the `input_features` tensor for one batch item.
   *
   * [constantBefore]: the first this-many samples are known to be identical (zero padding), so frames that fall
   * entirely inside them share one spectrum. 0 disables the shortcut.
   */
  fun features(pcm: ShortArray, len: Int = pcm.size, normalize: Boolean = true, constantBefore: Int = 0): FloatArray {
    val x = DoubleArray(len) { pcm[it] / 32768.0 }
    if (normalize) {
      var mean = 0.0
      for (v in x) mean += v
      mean /= len
      var variance = 0.0
      for (v in x) { val d = v - mean; variance += d * d }
      variance /= len
      val inv = 1.0 / sqrt(variance + 1e-7)
      for (i in x.indices) x[i] = (x[i] - mean) * inv
    }
    val nFrames = frames(len)
    val pad = N_FFT / 2
    // reflect padding: x[-i] = x[i], x[len-1+i] = x[len-1-i]
    fun sample(i: Int): Double = when {
      i < 0 -> x[-i]
      i >= len -> x[2 * (len - 1) - i]
      else -> x[i]
    }
    // Frames wholly inside the constant prefix (the reflected left edge is that same constant).
    // Frame t covers samples [t*HOP - pad, t*HOP - pad + N_FFT); it is constant while its end <= constantBefore.
    val constantFrames =
      if (constantBefore >= N_FFT - pad) ((constantBefore - (N_FFT - pad)) / HOP + 1).coerceIn(0, nFrames) else 0

    val out = FloatArray(N_MELS * nFrames)
    val logSpec = DoubleArray(N_MELS * nFrames)
    val fft = Fft400()
    val re = DoubleArray(N_FFT)
    val im = DoubleArray(N_FFT)
    val melRow = DoubleArray(N_MELS)
    var maxLog = Double.NEGATIVE_INFINITY

    fun frameLogMel(t: Int) {
      val start = t * HOP - pad
      for (n in 0 until N_FFT) { re[n] = sample(start + n) * window[n]; im[n] = 0.0 }
      fft.transform(re, im)
      java.util.Arrays.fill(melRow, 0.0)
      for (k in 0 until N_BINS) {
        val p = re[k] * re[k] + im[k] * im[k]
        if (p == 0.0) continue
        val base = k * N_MELS
        for (m in 0 until N_MELS) melRow[m] += p * mel[base + m]
      }
      for (m in 0 until N_MELS) {
        val v = log10(max(melRow[m], 1e-10))
        logSpec[m * nFrames + t] = v
        if (v > maxLog) maxLog = v
      }
    }

    if (constantFrames > 0) {
      frameLogMel(0)
      for (t in 1 until constantFrames) for (m in 0 until N_MELS) logSpec[m * nFrames + t] = logSpec[m * nFrames]
    }
    for (t in constantFrames until nFrames) frameLogMel(t)

    val floor = maxLog - 8.0
    for (i in out.indices) out[i] = ((max(logSpec[i], floor) + 4.0) / 4.0).toFloat()
    return out
  }

  /**
   * In-place complex FFT of length 400 by recursive decimation in time over the radices 2,2,2,2,5,5.
   * Exact for this length (no zero-padding), ~10x cheaper than the direct DFT it replaces.
   */
  class Fft400 {
    private val n = N_FFT
    private val cosT = DoubleArray(n) { cos(-2.0 * PI * it / n) }
    private val sinT = DoubleArray(n) { sin(-2.0 * PI * it / n) }
    // Transform lengths by recursion depth: 400, 200, 100, 50, 25, 5, 1. Calls at one depth run one after
    // another, so a single scratch pair per depth serves the whole recursion without allocation.
    private val sizes = intArrayOf(400, 200, 100, 50, 25, 5, 1)
    private val outRe = DoubleArray(n)
    private val outIm = DoubleArray(n)
    private val tmpRe = Array(sizes.size) { DoubleArray(sizes[it]) }
    private val tmpIm = Array(sizes.size) { DoubleArray(sizes[it]) }

    fun transform(re: DoubleArray, im: DoubleArray) {
      rec(re, im, 0, 1, n, outRe, outIm, 0, 0)
      System.arraycopy(outRe, 0, re, 0, n); System.arraycopy(outIm, 0, im, 0, n)
    }

    private fun rec(
      inRe: DoubleArray, inIm: DoubleArray, off: Int, stride: Int, len: Int,
      outRe: DoubleArray, outIm: DoubleArray, outOff: Int, depth: Int,
    ) {
      if (len == 1) { outRe[outOff] = inRe[off]; outIm[outOff] = inIm[off]; return }
      val r = if (len % 2 == 0) 2 else 5
      val m = len / r
      for (j in 0 until r) rec(inRe, inIm, off + j * stride, stride * r, m, outRe, outIm, outOff + j * m, depth + 1)
      // Combine the r sub-transforms: X[k + q*m] = sum_j W_len^(j*(k+q*m)) * Y_j[k]
      val tmpRe = tmpRe[depth]; val tmpIm = tmpIm[depth]
      val twiddleStep = n / len
      for (q in 0 until r) for (k in 0 until m) {
        val idx = k + q * m
        var sr = 0.0; var si = 0.0
        for (j in 0 until r) {
          val yr = outRe[outOff + j * m + k]; val yi = outIm[outOff + j * m + k]
          val e = ((j * idx) % len) * twiddleStep
          val wr = cosT[e]; val wi = sinT[e]
          sr += yr * wr - yi * wi; si += yr * wi + yi * wr
        }
        tmpRe[idx] = sr; tmpIm[idx] = si
      }
      System.arraycopy(tmpRe, 0, outRe, outOff, len); System.arraycopy(tmpIm, 0, outIm, outOff, len)
    }
  }
}
