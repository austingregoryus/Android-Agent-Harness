#!/usr/bin/env python3
"""Assemble a flashable Magisk module zip for the Android Agent Harness privileged install.

Bundles a release APK, the privapp-permissions XML, and module.prop into the minimal
Magisk module zip layout (module.prop + system/... + META-INF/com/google/android/{update-binary,updater-script}).
Flash the resulting zip from the Magisk app ("Install from storage") or from custom recovery.

See docs/adding-a-phone.md, section "Privileged install (rooted phones, needed for talking calls)".

Usage:
    python tools/privapp/build_module.py --apk path/to/app-release.apk --out android-agent-harness-privapp.zip
    python tools/privapp/build_module.py --apk app-release.apk --out mod.zip \
        --xml tools/privapp/privapp-permissions-symbiosis.xml --prop tools/privapp/module.prop

All paths default relative to this script's own directory (tools/privapp/), so it can be run from
anywhere. Pure standard library — no dependencies, runs on Windows, macOS or Linux.
"""

from __future__ import annotations

import argparse
import sys
import zipfile
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent

APP_ID = "dev.symbiosis.runtime"
APK_ARCNAME = f"system/priv-app/Symbiosis/Symbiosis.apk"
XML_ARCNAME = "system/etc/permissions/privapp-permissions-symbiosis.xml"
PROP_ARCNAME = "module.prop"

# Standard Magisk module template installer: a module zip is not a full flashable OTA, so
# update-binary just hands off to Magisk's own install_module() once Magisk is confirmed present.
# updater-script is the fixed "#MAGISK" sentinel Magisk's manager (and magiskboot --install) look for
# to recognize a module zip rather than a legacy flashable zip.
UPDATE_BINARY = """#!/sbin/sh
##########################################################################################
# Android Agent Harness privapp module installer (generated by tools/privapp/build_module.py)
# Standard Magisk module template update-binary: https://github.com/topjohnwu/magisk-module-template
##########################################################################################

umask 022

ui_print() { echo "$1"; }

require_new_magisk() {
  ui_print "*******************************"
  ui_print " Please install Magisk v20.4+! "
  ui_print "*******************************"
  exit 1
}

OUTFD=$2
ZIPFILE=$3

mount /data 2>/dev/null

[ -f /data/adb/magisk/util_functions.sh ] || require_new_magisk
. /data/adb/magisk/util_functions.sh
[ "$MAGISK_VER_CODE" -lt 20400 ] && require_new_magisk

install_module
exit 0
"""

UPDATER_SCRIPT = "#MAGISK\n"


def build(apk: Path, xml: Path, prop: Path, out: Path) -> None:
    for label, p in (("APK", apk), ("privapp-permissions XML", xml), ("module.prop", prop)):
        if not p.is_file():
            raise SystemExit(f"error: {label} not found: {p}")

    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("META-INF/com/google/android/update-binary", UPDATE_BINARY)
        z.writestr("META-INF/com/google/android/updater-script", UPDATER_SCRIPT)
        z.write(prop, PROP_ARCNAME)
        z.write(apk, APK_ARCNAME)
        z.write(xml, XML_ARCNAME)

    print(f"wrote {out}")
    with zipfile.ZipFile(out) as z:
        for name in z.namelist():
            print(f"  {name}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--apk", required=True, type=Path, help="Release APK to embed (e.g. app-release.apk)")
    ap.add_argument("--xml", type=Path, default=SCRIPT_DIR / "privapp-permissions-symbiosis.xml",
                     help="privapp-permissions XML (default: tools/privapp/privapp-permissions-symbiosis.xml)")
    ap.add_argument("--prop", type=Path, default=SCRIPT_DIR / "module.prop",
                     help="module.prop (default: tools/privapp/module.prop)")
    ap.add_argument("--out", type=Path, default=Path("android-agent-harness-privapp.zip"),
                     help="Output zip path (default: ./android-agent-harness-privapp.zip)")
    args = ap.parse_args(argv)

    build(args.apk, args.xml, args.prop, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
